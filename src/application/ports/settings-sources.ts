// Порты слоёв настроек редактора (R-ADM, [owner 2026-10-22]). Адаптеры
// только читают/пишут сырой JSON; разбор и проверка — у ядра настроек
// (resolve-settings) по секциям. Как и IKeybindingsStorage раньше: смена
// хранилища (файл → бэкенд) — новый адаптер в container.ts, остальной код
// не меняется.

/**
 * Настройки администратора — общие для всех пользователей стенда. Сейчас —
 * JSON-файл рядом со сборкой (public/config), потом — бэкенд (JSON-строка
 * из базы); формат документа один.
 */
export interface IAdminSettingsSource {
  /** Документ настроек; null — администратор ничего не переопределял. */
  load(): Promise<unknown>;
  /**
   * Следить за изменениями: onChange получает новый документ, только когда
   * он действительно изменился. Возвращает отписку.
   */
  watch(onChange: (raw: unknown) => void): () => void;
}

/** Личные настройки пользователя (секции со scope `user`) — на его устройстве. */
export interface IUserSettingsStorage {
  /** Документ настроек; null — пользователь ничего не менял. */
  load(): unknown;
  save(raw: unknown): void;
}
